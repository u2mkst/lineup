import type { Drawing, Pt } from '../types';

/** One step of a set piece. `us[i]` is token `u{i}` (0 = goalkeeper, 1-4 back line, 5-8 midfield, 9-10 forwards). */
export interface TemplateFrame {
  note: string;
  us: Pt[];
  /** used when the opponent is switched on */
  opp?: Pt[];
  ball: Pt;
  /** token id that has the ball, e.g. `u9` */
  holder?: string | null;
  /** curved paths into this frame */
  via?: Record<string, Pt>;
  drawings?: Omit<Drawing, 'id'>[];
}

export interface SetPiece {
  id: string;
  title: string;
  desc: string;
  frames: TemplateFrame[];
}

const P = (x: number, y: number): Pt => ({ x, y });
export const mirror = (p: Pt): Pt => ({ x: 1 - p.x, y: 1 - p.y });
const pass = (a: Pt, b: Pt) => ({ kind: 'pass' as const, a, b });
const run = (a: Pt, b: Pt) => ({ kind: 'run' as const, a, b });
const zone = (c: Pt, edge: Pt) => ({ kind: 'zone' as const, a: c, b: edge });

